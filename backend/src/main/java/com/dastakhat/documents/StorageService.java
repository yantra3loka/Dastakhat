package com.dastakhat.documents;

import com.dastakhat.common.ApiException;
import com.dastakhat.common.Hashing;
import com.dastakhat.config.AppProperties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Stores documents outside of any web root under a random, opaque key.
 *
 * <p>The key is generated by the server. A user supplied file name is only kept as a
 * sanitised display name and is never used to build a path, which rules out path
 * traversal.</p>
 */
@Service
public class StorageService {

    private static final Logger log = LoggerFactory.getLogger(StorageService.class);

    /** Only keys that match this pattern are ever resolved to a file. */
    private static final Pattern VALID_KEY = Pattern.compile("^[0-9a-f]{32}(\\.[a-z0-9]{1,8})?$");

    private final Path root;

    public StorageService(AppProperties properties) {
        this.root = Path.of(properties.getStorageDir()).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot create storage directory " + root, e);
        }
        log.info("Document storage root: {}", root);
    }

    /** Stores the given bytes and returns the random storage key. */
    public String store(byte[] data, String extension) {
        String key = Hashing.toHex(Hashing.randomBytes(16)) + (extension == null ? "" : "." + extension);
        Path target = resolve(key);
        try {
            Files.write(target, data);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot store document", e);
        }
        return key;
    }

    /** Stores the content of the given stream. */
    public String store(InputStream in, String extension) throws IOException {
        return store(in.readAllBytes(), extension);
    }

    /** Reads the document with the given key. */
    public byte[] read(String key) {
        Path path = resolve(key);
        try {
            return Files.readAllBytes(path);
        } catch (IOException e) {
            throw new ApiException(HttpStatus.NOT_FOUND.value(), "not_found", "The document is not available.");
        }
    }

    /** True when a document with the given key exists. */
    public boolean exists(String key) {
        try {
            return Files.exists(resolve(key));
        } catch (ApiException e) {
            return false;
        }
    }

    /** Removes a stored document. Missing files are ignored. */
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException | ApiException e) {
            log.warn("Could not delete stored document {}", key, e);
        }
    }

    /**
     * Resolves a storage key to a path. The key is validated against a strict pattern and the
     * resulting path is verified to stay inside the storage root.
     */
    public Path resolve(String key) {
        if (key == null || !VALID_KEY.matcher(key.toLowerCase(Locale.ROOT)).matches()) {
            throw new ApiException(HttpStatus.NOT_FOUND.value(), "not_found", "The document is not available.");
        }
        Path target = root.resolve(key).normalize();
        if (!target.startsWith(root)) {
            throw new ApiException(HttpStatus.NOT_FOUND.value(), "not_found", "The document is not available.");
        }
        return target;
    }

    /** Copies a file from one storage key to another (used to promote the working document). */
    public String copy(String sourceKey, String destinationKey) {
        try {
            Files.copy(resolve(sourceKey), resolve(destinationKey), StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot copy stored document", e);
        }
        return destinationKey;
    }

    /** Strips every path separator and control character from an uploaded file name. */
    public static String sanitizeFilename(String filename) {
        if (filename == null || filename.isBlank()) {
            return "document.pdf";
        }
        String name = filename.replace('\\', '/');
        name = name.substring(name.lastIndexOf('/') + 1);
        name = name.replaceAll("[\\p{Cntrl}]", "").replaceAll("[^A-Za-z0-9 ._-]", "_");
        name = name.trim();
        if (name.isEmpty()) {
            return "document.pdf";
        }
        if (name.length() > 200) {
            name = name.substring(0, 200);
        }
        return name;
    }
}
